def _list(v):
    """Allow compact 'a|b|c' strings for list fields."""
    if isinstance(v, str):
        return [x.strip() for x in v.split("|") if x.strip()]
    return list(v or [])


def S(slug, title, category, difficulty, board, parts, comms, *,
      problem, outcome, objectives, use_cases, algorithm, logic,
      tests, fails, hours, free=False, free_rank=None, pins=None, cloud="",
      calibration="", deployment="", safety="", limitations="",
      improvements=None, advanced=False, optional_parts=None, refs=None,
      summary=None, prereqs=None, skills=None, status="published", quality=None):
    """Declare one project. ``tests`` and ``fails`` are project-specific."""
    return {
        "slug": slug, "title": title, "category": category, "difficulty": difficulty,
        "board": board, "parts": parts, "comms": comms, "problem": problem,
        "outcome": outcome, "objectives": _list(objectives), "use_cases": _list(use_cases),
        "algorithm": algorithm, "logic": logic, "tests": _list(tests), "fails": _list(fails),
        "hours": hours, "free": free, "free_rank": free_rank, "pins": pins or {},
        "cloud": cloud, "calibration": calibration, "deployment": deployment,
        "safety": safety, "limitations": limitations, "improvements": improvements or [],
        "advanced": advanced, "optional_parts": optional_parts or [], "refs": refs or [],
        "summary": summary, "prereqs": prereqs, "skills": skills,
        "status": status, "quality": quality,
    }
